import { expect, test } from '@playwright/test'
import { registerAndLogin, waitForHydration } from './helpers'

test('首次导览完成后不重复提示，帮助中心支持搜索、重看及跳转个人资料', async ({ page, request }, testInfo) => {
  await registerAndLogin(page, request, 'guide', { keepGuide: true })
  await expect(page.getByTestId('guide-offer')).toBeVisible()
  await page.getByTestId('guide-start').click()
  const popover = page.locator('.hai-guide-popover')
  await expect(popover).toBeVisible()
  await expect(popover.locator('.driver-popover-progress-text')).toContainText('1')
  await expect(popover.locator('.driver-popover-next-btn')).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('admin-guide-desktop.png'), fullPage: true, animations: 'disabled' })
  for (let step = 1; step < 4; step++) {
    await popover.locator('.driver-popover-next-btn').click()
    await expect(popover.locator('.driver-popover-progress-text')).toContainText(String(step + 1))
  }
  await popover.locator('.driver-popover-next-btn').click()
  await expect(popover).toHaveCount(0)
  await page.reload()
  await waitForHydration(page)
  await expect(page.getByTestId('guide-offer')).toHaveCount(0)
  await page.getByTestId('admin-help').click()
  await expect(page.getByTestId('guide-help')).toBeVisible()
  await page.getByTestId('guide-search').locator('input').fill('密码')
  await expect(page.getByTestId('guide-article-profile')).toBeVisible()
  await page.getByTestId('guide-tour-profile').click()
  await expect(page).toHaveURL(/\/admin\/profile/)
  await expect(popover.locator('.driver-popover-title')).toContainText(/个人资料|profile/i)
  await expect(page.getByTestId('guide-help')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(popover).toHaveCount(0)
  await page.getByTestId('admin-help').click()
  await page.getByTestId('guide-tour-overview').click()
  await expect(page).toHaveURL(/\/admin$/)
  await expect(popover).toBeVisible()
  await expect(popover.locator('.driver-popover-next-btn')).toBeEnabled()
  // 模拟下一步异步目标尚未出现，验证遮罩下的取消按钮仍可点击。
  await page.locator('[data-guide="admin-theme"]').evaluate(element => element.removeAttribute('data-guide'))
  await popover.locator('.driver-popover-next-btn').click()
  await expect(page.getByTestId('guide-loading')).toBeVisible()
  await page.getByTestId('guide-cancel').click()
  await expect(popover).toHaveCount(0)
  await expect(page.getByTestId('guide-error')).toHaveCount(0)
})

