  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin/)
  await context.clearCookies()
  await open(page)
  await page.locator('a[href="/auth/register"]').click()
  await waitForHydration(page)
  await page.getByRole('button', { name: '用户协议', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '用户协议' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading', { name: '配置中的用户协议' })).toBeVisible()
  await expect(dialog.getByText('注册须知', { exact: true })).toBeVisible()
  await expect(page.locator('iframe')).toHaveCount(0)
  await screenshot(page, 'admin-agreement')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: '隐私政策', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '隐私政策' })).toBeVisible()
  await expect(page.frameLocator('iframe').getByRole('heading', { name: 'Test agreement' })).toBeVisible()
  await screenshot(page, 'admin-privacy')
  await page.keyboard.press('Escape')
  await screenshot(page, 'admin-register')
  await page.locator('input[name="username"]').fill(username)
  await page.locator('input[name="email"]').fill(email)
  await page.locator('input[type="password"]').nth(0).fill(password)
  await page.locator('input[type="password"]').nth(1).fill(password)
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin/)
  await context.clearCookies()
  await open(page)
  await page.getByRole('button', { name: '邮件验证码', exact: true }).click()
  await screenshot(page, 'admin-email-code')
  await page.locator('#login-username').fill(email)
  await page.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(page.getByRole('button', { name: /秒后重发/ })).toBeDisabled()
  const sent = await notification(page, email, 'otp_email')
  expect(Boolean(sent?.code)).toBe(true)
  await page.locator('#login-code').fill(sent?.code ?? '')
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin/)
  await context.clearCookies()
  await open(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '短信验证码', exact: true }).click()
  await screenshot(page, 'admin-sms-mobile')
  const phone = `139${String(suffix).slice(-8)}`
  await page.locator('#login-username').fill(phone)
  await page.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(page.getByRole('button', { name: /秒后重发/ })).toBeDisabled()
  const sms = await notification(page, phone, 'otp_sms')
  expect(Boolean(sms?.code)).toBe(true)
  await page.locator('#login-code').fill(sms?.code ?? '')
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin/)
  await context.clearCookies()
  await open(page, '/auth/forgot-password')
  await screenshot(page, 'admin-forgot-mobile')
  await page.locator('input[type="email"]').fill(email)
  await page.locator('button[type="submit"]').click()
  await expect(page.getByRole('heading', { name: /重置通知已发送|Reset Instructions Sent/i })).toBeVisible()
  const reset = await notification(page, email, 'password_reset')
  expect(Boolean(reset?.token)).toBe(true)
  await page.getByRole('link', { name: '重置密码', exact: true }).click()
  await expect(page.locator('#reset-code')).toBeVisible()
  await screenshot(page, 'admin-reset-mobile')
  await page.locator('#reset-code').fill(reset?.token ?? '')
  await page.locator('input[type="password"]').nth(0).fill('ResetPassword456')
  await page.locator('input[type="password"]').nth(1).fill('ResetPassword456')
  await page.locator('button[type="submit"]').click()
