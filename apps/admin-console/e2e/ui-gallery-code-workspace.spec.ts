import { expect, test } from '@playwright/test'
import { registerAndLogin, waitForHydration } from './helpers'

test('CodeWorkspace 通过文件树和搜索打开标签，并让选区联动宿主面板', async ({ page, request }, testInfo) => {
  const workerErrors: string[] = []
  const workerResponses = new Set<string>()
  page.on('console', (message) => {
    if (/could not create web worker|worker failed to load/i.test(message.text()))
      workerErrors.push(message.text())
  })
  page.context().on('response', (response) => {
    const url = new URL(response.url())
    const worker = /\/(editor|ts)\.worker-[^/]+\.js$/.exec(url.pathname)?.[1]
    if (worker && response.ok() && url.origin === new URL(page.url()).origin)
      workerResponses.add(worker)
  })

  await page.setViewportSize({ width: 1440, height: 1000 })
  await registerAndLogin(page, request, 'codework')
  await page.context().addCookies([
    { name: 'PARAGLIDE_LOCALE', value: 'en-US', url: new URL(page.url()).origin },
  ])
  await page.goto('/admin/ui-gallery/scenes')
  await waitForHydration(page)

  const demo = page.getByTestId('code-workspace-demo')
  const editor = demo.locator('.monaco-editor')
  const tree = demo.getByRole('tree', { name: 'Workspace files' })
  const inspector = demo.getByRole('region', { name: 'Code inspector' })
  const docs = tree.getByRole('treeitem', { name: 'docs' })
  const shared = tree.getByRole('treeitem', { name: 'shared' })
  const start = tree.getByRole('treeitem', { name: 'quick-start.md' })
  const rulesTab = demo.getByRole('tab', { name: /rules\.ts/ })
  await expect(editor).toBeVisible({ timeout: 15_000 })
  await expect.poll(() => editor.evaluate(element => element.clientHeight)).toBeGreaterThan(300)
  await expect.poll(() => [...workerResponses]).toEqual(expect.arrayContaining(['editor', 'ts']))
  await expect(rulesTab).toHaveAttribute('aria-selected', 'true')
  const riskIcon = demo.getByRole('button', { name: 'Redact review notes before logging them.', exact: true })
  const tip = demo.getByRole('button', { name: 'Toggle review tip' })
  await riskIcon.hover()
  await expect(tip).toBeVisible()
  await tip.click()
  await expect(demo.getByText('Redact each note before passing it to the logger.')).toBeVisible()
  await tip.press('Escape')
  await expect(tip).toBeHidden()
  await expect(riskIcon).toBeFocused()
  const gitIcon = demo.getByRole('button', { name: 'Uncommitted changes', exact: true })
  await gitIcon.hover()
  await expect(demo.getByText('This range includes uncommitted changes.')).toBeVisible()
  await gitIcon.press('Escape')
  await expect(docs.locator('[data-code-chevron]')).toHaveCount(1)
  await expect(docs.locator('[data-code-folder]')).toHaveCount(1)
  await expect(shared.locator('[data-code-chevron]')).toHaveCount(1)
  await expect(start).toHaveCount(0)
  await docs.press('ArrowRight')
  await expect(docs).toBeFocused()
  await expect(docs).toHaveAttribute('aria-busy', 'true')
  await expect(docs).toHaveAttribute('aria-expanded', 'true')
  await expect(start).toBeVisible()
  await expect(start.locator('[data-code-chevron]')).toHaveCount(0)
  await expect(docs).toBeFocused()
  await docs.press('ArrowRight')
  await expect(start).toBeFocused()
  await start.press('Enter')
  await expect(demo.getByRole('tab', { name: /quick-start\.md/ })).toHaveAttribute('aria-selected', 'true')
  await expect(editor.locator('.view-lines')).toContainText('Quick start')

  // shared 仍未展开，内容搜索应直接命中文件并把编辑器定位到匹配范围。
  await expect(shared).toHaveAttribute('aria-expanded', 'false')
  await demo.getByRole('button', { name: 'Search content', exact: true }).click()
  const workspaceSearch = demo.getByRole('searchbox', { name: 'Search workspace content' })
  await workspaceSearch.fill('confidential preview')
  await demo.getByRole('button', { name: 'redact.ts, line 3, column 9' }).click()
  const redactTab = demo.getByRole('tab', { name: /redact\.ts/ })
  await expect(redactTab).toHaveAttribute('aria-selected', 'true')
  await expect(inspector.getByText('src/shared/redact.ts', { exact: true })).toBeVisible()
  await expect(editor.locator('.view-lines')).toContainText('Hide confidential preview text.')
  await expect(inspector.getByText('Example analysis · L3')).toBeVisible()
  await expect(workspaceSearch).toHaveValue('confidential preview')

  await demo.getByRole('button', { name: 'Find files', exact: true }).click()
  const fileSearch = demo.getByRole('searchbox', { name: 'Search by name or path' })
  await fileSearch.fill('src/index')
  await demo.getByRole('button', { name: 'index.ts src' }).click()
  await expect(demo.getByRole('tab', { name: /index\.ts/ })).toHaveAttribute('aria-selected', 'true')
  await expect(rulesTab).toBeVisible()
  await expect(redactTab).toBeVisible()
  await demo.getByRole('button', { name: /Close.*redact\.ts/i }).click()
  await expect(redactTab).toHaveCount(0)

  await rulesTab.click()
  await expect(editor.locator('.view-lines')).toContainText('console.debug(review.notes)')
  await demo.getByRole('button', { name: 'Find in file', exact: true }).click()
  const find = editor.locator('.find-widget textarea, .find-widget input[type="text"]').first()
  await find.fill('notes')
  await expect(editor.locator('.find-widget .matchesCount')).toHaveText(/\d+ of [2-9]/i)
  await find.press('Escape')
  await demo.getByRole('button', { name: 'Go to line', exact: true }).click()
  const lineInput = demo.locator('.quick-input-widget input')
  await lineInput.fill(':9')
  await lineInput.press('Enter')
  await expect(demo.locator('.quick-input-widget')).toBeHidden()
  await expect(editor.locator('.active-line-number')).toHaveText('9')

  await demo.getByRole('button', { name: 'View line 9', exact: true }).click()
  await expect(inspector.getByText('Example analysis · L9')).toBeVisible()
  await expect(inspector.getByText('console.debug(review.notes)', { exact: true })).toBeVisible()
  const editorInput = editor.getByRole('textbox', { name: 'Code editor · rules.ts' })
  await editorInput.press('Home')
  await editorInput.press('Shift+End')
  await editorInput.press('Alt+Shift+Enter')
  const mark = demo.getByRole('button', { name: 'Mark selection', exact: true })
  await expect(mark).toBeFocused()
  await mark.press('Enter')
  await expect(inspector.getByText('Marked selection · L9')).toBeVisible()

  await demo.getByRole('button', { name: 'File tree', exact: true }).click()
  const splitter = demo.getByRole('separator', { name: 'Resize file explorer' })
  const width = Number(await splitter.getAttribute('aria-valuenow'))
  await splitter.press('ArrowLeft')
  await expect(splitter).toHaveAttribute('aria-valuenow', String(width - 12))
  await splitter.press('Enter')
  await expect(tree).toBeHidden()
  await demo.getByRole('button', { name: 'File explorer', exact: true }).click()
  await expect(tree).toBeVisible()
  await expect(splitter).toHaveAttribute('aria-valuenow', String(width - 12))

  const display = demo.locator('summary[aria-label="Display options"]')
  await display.click()
  const editorTheme = demo.getByRole('combobox', { name: 'Editor theme' })
  await editorTheme.selectOption('github-dark')
  await expect(editor.locator('.monaco-editor-background').first()).toHaveCSS('background-color', 'rgb(13, 17, 23)')

  await display.click()
  await demo.screenshot({
    path: testInfo.outputPath('code-workspace.png'),
    animations: 'disabled',
  })

  await display.click()
  await editorTheme.selectOption('inherit')
  await display.click()
  await page.getByRole('button', { name: 'Select theme' }).click()
  await page.locator('[data-theme-option="dark"]').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(editor.locator('.monaco-editor-background').first()).toHaveCSS('background-color', 'rgb(30, 30, 30)')
  expect(workerErrors).toEqual([])
})
