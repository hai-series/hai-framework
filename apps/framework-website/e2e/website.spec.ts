import { expect, test } from '@playwright/test'

test('官网在仓库子路径呈现，模板预览、导航、全文搜索与深链刷新可用', async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/hai-framework/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('从一个想法')
  const previews = page.locator('[data-template-preview]')
  await expect(previews).toHaveCount(4)
  for (const preview of await previews.all()) {
    const screenshot = preview.locator('img')
    await screenshot.scrollIntoViewIfNeeded()
    await expect(screenshot).toHaveJSProperty('complete', true)
    expect(await screenshot.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    const href = await preview.getByRole('link').getAttribute('href')
    const target = new URL(href!, page.url())
    expect(target.origin).toBe(new URL(page.url()).origin)
    expect(target.pathname).toMatch(/^\/hai-framework\/(?:guide-images|template-previews)\//)
    expect((await request.get(target.href)).status()).toBe(200)
  }
  for (const link of await page.locator('.feature-card > a').all()) {
    const href = await link.getAttribute('href')
    expect((await request.get(new URL(href!, page.url()).href)).status()).toBe(200)
  }
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('website-home-overview.png'), fullPage: true })
  await page.locator('#template-previews').evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: testInfo.outputPath('website-templates-desktop.png'), fullPage: false })
  const originalPage = page.waitForEvent('popup')
  await previews.first().getByRole('link').click()
  const original = await originalPage
  await expect(original).toHaveURL(/\/hai-framework\/template-previews\/fullstack-users\.png$/)
  await original.close()
  await page.getByRole('button', { name: '搜索文档', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('searchbox').fill('maxAge')
  await expect(dialog.locator('.search-results a').first()).toBeVisible()
  await dialog.locator('.search-results a').filter({ hasText: '登录、密码' }).first().click()
  await expect(page).toHaveURL(/\/hai-framework\/docs\/configuration\/identity\//)
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('登录、密码')
  const sidebar = page.locator('.documentation-sidebar')
  await expect(sidebar.locator('.doc-chapter[open]')).toHaveCount(1)
  await expect(sidebar.locator('[data-doc-section="configuration"]')).toHaveAttribute('open')
  await expect(sidebar.getByRole('link', { name: '身份、会话与安全策略' })).toHaveAttribute('aria-current', 'page')
  const onThisPage = page.getByRole('navigation', { name: '本页内容' })
  await onThisPage.getByRole('link', { name: '会话有效期与终端配额' }).click()
  await expect(page.locator('#会话有效期与终端配额')).toBeInViewport()
  await expect(page.locator('.site-header')).toBeInViewport()
  const image = page.locator('article img').first()
  await image.scrollIntoViewIfNeeded()
  await expect(image).toHaveJSProperty('complete', true)
  expect(await image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: testInfo.outputPath('website-documentation.png'), fullPage: false })
  await sidebar.locator('[data-doc-section="configuration"] > summary').click()
  await page.getByRole('button', { name: '搜索文档', exact: true }).click()
  await dialog.getByRole('searchbox').fill('maxAge')
  await dialog.locator('.search-results a').filter({ hasText: '登录、密码' }).first().click()
  await expect(sidebar.locator('[data-doc-section="configuration"]')).toHaveAttribute('open')
  await sidebar.locator('[data-doc-section="operations"] > summary').click()
  await sidebar.getByRole('link', { name: '全量、增量与发布后回退' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('应用部署')
  await expect(sidebar.locator('.doc-chapter[open]')).toHaveCount(1)
  await expect(sidebar.locator('[data-doc-section="operations"]')).toHaveAttribute('open')
  expect(errors).toEqual([])
})

